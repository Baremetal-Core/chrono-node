#!/usr/bin/env python3
"""Generate the Vietnamese lunar calendar table (src/lunar_table.h).

Months start on the day (UTC+7) of the new moon; month 11 contains the winter
solstice; in a 13-month year the first month without a major solar term (a
30-degree step of the sun's longitude) is the leap month. New moons and solar
terms come from NASA JPL's DE440s ephemeris via Skyfield, so the table is
exact where the firmware's formula can be a day off (new moons within a
minute of midnight). Downloads de440s.bsp (32 MB) to ~/.cache/skyfield once.

Usage (from the repository root):
    uv run --with skyfield tools/gen_lunar_table.py
"""
from __future__ import annotations

import bisect
import datetime as dt
from pathlib import Path

from skyfield import almanac
from skyfield.api import Loader
from skyfield.framelib import ecliptic_frame

FIRST, LAST = 1900, 2100  # lunar years in the table
OUT = Path(__file__).resolve().parent.parent / "src" / "lunar_table.h"
TZ = dt.timedelta(hours=7)


def main() -> None:
    load = Loader(Path.home() / ".cache" / "skyfield")
    ts = load.timescale()
    eph = load("de440s.bsp")
    t0, t1 = ts.utc(FIRST - 2, 1, 1), ts.utc(LAST + 2, 6, 1)

    def local_day(t) -> int:  # proleptic Gregorian ordinal of the UTC+7 date
        return (t.utc_datetime() + TZ).date().toordinal()

    times, phases = almanac.find_discrete(t0, t1, almanac.moon_phases(eph))
    new_moons = sorted(local_day(t) for t, p in zip(times, phases) if p == 0)

    earth, sun = eph["earth"], eph["sun"]

    def segment(t):
        _, lon, _ = earth.at(t).observe(sun).apparent().frame_latlon(ecliptic_frame)
        return (lon.degrees // 30).astype(int)

    segment.step_days = 10
    times, values = almanac.find_discrete(t0, t1, segment)
    terms = [(local_day(t), int(v)) for t, v in zip(times, values)]
    term_days = [d for d, _ in terms]

    def month_of(day: int) -> int:
        return bisect.bisect_right(new_moons, day) - 1

    def has_term(i: int) -> bool:
        j = bisect.bisect_left(term_days, new_moons[i])
        return j < len(term_days) and term_days[j] < new_moons[i + 1]

    # Number the months between consecutive months 11 (winter solstice = 270°).
    month11 = sorted({month_of(d) for d, v in terms if v == 9})
    label: dict[int, tuple[int, bool]] = {}
    for a, b in zip(month11, month11[1:]):
        leap = None
        if b - a == 13:
            leap = next(i for i in range(a + 1, b + 1) if not has_term(i))
        number, prev = 11, 11
        for i in range(a, b):
            if i == leap:
                label[i] = (prev, True)
            else:
                label[i] = (number, False)
                prev, number = number, number % 12 + 1

    entries = []
    for year in range(FIRST, LAST + 1):
        jan1 = dt.date(year, 1, 1).toordinal()
        first = next(i for i in sorted(label) if new_moons[i] >= jan1 and label[i] == (1, False))
        months, i = [], first
        while True:
            months.append((new_moons[i + 1] - new_moons[i], label[i][1], label[i][0]))
            i += 1
            if label[i] == (1, False):
                break
        assert len(months) in (12, 13)
        leap_month = next((m for _, leap, m in months if leap), 0)
        lengths = sum(1 << k for k, (n, _, _) in enumerate(months) if n == 30)
        offset = new_moons[first] - jan1  # Tết: days after 1 January
        assert 0 <= offset < 64 and all(n in (29, 30) for n, _, _ in months)
        entries.append(lengths | leap_month << 13 | offset << 17)

    lines = [
        "// Generated by tools/gen_lunar_table.py - do not edit.",
        f"// Vietnamese lunar years {FIRST}-{LAST} (UTC+7) from NASA JPL DE440s. Per year:",
        "// bits 0-12 month lengths in order (1 = 30 days), bits 13-16 the leap month",
        "// (it follows that month; 0 = none), bits 17-22 Tết's day after 1 January.",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "namespace lunar {",
        "",
        f"constexpr int kTableFirstYear = {FIRST};",
        f"constexpr int kTableLastYear = {LAST};",
        f"constexpr uint32_t kTable[{len(entries)}] = {{",
    ]
    for k in range(0, len(entries), 6):
        lines.append("    " + ", ".join(f"0x{e:06X}" for e in entries[k : k + 6]) + ",")
    lines += ["};", "", "}  // namespace lunar", ""]
    OUT.write_text("\n".join(lines))
    print(f"{OUT.relative_to(OUT.parent.parent)}: {len(entries)} years, {len(entries) * 4} bytes")


if __name__ == "__main__":
    main()
