#!/usr/bin/env python3
"""Generate the TLS root CA bundle used by Chrono Node for HTTPS.

Usage (from the repository root):
    uv run --with cryptography tools/gen_ca_bundle.py

Downloads Mozilla's root store as published by curl (https://curl.se/ca/cacert.pem)
and writes src/certs/ca_bundle.h in the ESP x509 certificate bundle format read
by WiFiClientSecure::setCACertBundle():

    u16 certificate count (big-endian), then per certificate, sorted by subject:
    u16 subject length, u16 public key length, subject (DER), public key (DER)

Only names and public keys are stored, so the bundle is much smaller than the
PEM file. The generated header is committed so builds need no network access.
"""

import re
import struct
import urllib.request
from pathlib import Path

from cryptography import x509
from cryptography.hazmat.primitives import serialization

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "certs" / "ca_bundle.h"
SOURCE = "https://curl.se/ca/cacert.pem"


def main():
    pem = urllib.request.urlopen(SOURCE, timeout=30).read().decode()
    as_of = re.search(r"Certificate data from Mozilla as of: (.+)", pem)
    certs = x509.load_pem_x509_certificates(pem.encode())

    entries = []
    for cert in certs:
        name = cert.subject.public_bytes()
        key = cert.public_key().public_bytes(
            serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo)
        entries.append((name, key))
    entries.sort(key=lambda e: e[0])

    data = bytearray(struct.pack(">H", len(entries)))
    for name, key in entries:
        data += struct.pack(">HH", len(name), len(key)) + name + key

    lines = [
        "// Generated by tools/gen_ca_bundle.py - do not edit.",
        f"// Mozilla root store via {SOURCE}",
        f"// as of {as_of.group(1).strip() if as_of else 'unknown'}: {len(entries)} roots, {len(data)} bytes.",
        "#pragma once",
        "",
        "#include <pgmspace.h>",
        "#include <stdint.h>",
        "",
        "const uint8_t ca_bundle[] PROGMEM = {",
    ]
    for i in range(0, len(data), 24):
        lines.append("  " + ", ".join(f"0x{b:02X}" for b in data[i:i + 24]) + ",")
    lines.append("};")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{OUT.relative_to(ROOT)}: {len(entries)} roots, {len(data)} bytes")


if __name__ == "__main__":
    main()
