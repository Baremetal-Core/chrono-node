#!/usr/bin/env python3
"""Generate TFT_eSPI smooth (VLW) fonts as C arrays for Chrono Node.

Usage (from the repository root):
    uv run --with freetype-py tools/gen_fonts.py

Reads the Inter variable font from tools/fonts/ (SIL OFL 1.1) and writes
src/fonts/*.h. The generated headers are committed so firmware builds do not
need Python or FreeType.

VLW layout (all integers big-endian int32), as read by TFT_eSPI loadFont():
    header : glyph count, version (11), size, 0, ascent, descent
    glyphs : unicode, height, width, xAdvance, dY (top above baseline), dX, 0
    bitmaps: width*height 8-bit alpha per glyph, in glyph order
"""

import struct
from pathlib import Path

import freetype

ROOT = Path(__file__).resolve().parent.parent
FONT_FILE = ROOT / "tools" / "fonts" / "Inter-Variable.ttf"
OUT_DIR = ROOT / "src" / "fonts"

ASCII = "".join(chr(c) for c in range(0x21, 0x7F))
# Vietnamese: precomposed vowels with tone marks plus ă â đ ê ô ơ ư.
VIETNAMESE = ("ÀÁÂÃÈÉÊÌÍÒÓÔÕÙÚÝàáâãèéêìíòóôõùúýĂăĐđĨĩŨũƠơƯư"
              + "".join(chr(c) for c in range(0x1EA0, 0x1EFA)))
# Punctuation that phones and editors insert automatically: – — ‘ ’ “ ” • …
PUNCT = "\u2013\u2014\u2018\u2019\u201c\u201d\u2022\u2026"
DIGITS = "0123456789"

# name, pixel size, weight (100-900), optical size (14-32), characters
FONTS = [
    ("font_time", 104, 700, 32, DIGITS + ":"),
    ("font_seconds", 26, 700, 24, DIGITS),
    ("font_date", 20, 500, 20, ASCII + "\u00b0\u00b7" + PUNCT + VIETNAMESE),
    ("font_temp", 54, 700, 32, DIGITS + "-\u00b0"),
    ("font_face", 24, 700, 24, ASCII + "\u00b0\u00b7"),  # clock face: date, weather temperature
    ("font_small", 15, 500, 14, ASCII + "\u00b0\u00b7" + PUNCT + VIETNAMESE),
]


def render_vlw(px, weight, opsz, chars):
    face = freetype.Face(str(FONT_FILE))
    face.set_var_design_coords((opsz, weight))
    face.set_pixel_sizes(0, px)
    ascent = face.size.ascender >> 6
    descent = -(face.size.descender >> 6)

    metrics = bytearray()
    bitmaps = bytearray()
    codepoints = sorted(set(ord(c) for c in chars))
    for cp in codepoints:
        face.load_char(chr(cp), freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_LIGHT)
        g = face.glyph
        bm = g.bitmap
        if bm.width > 255 or bm.rows > 255:
            raise ValueError(f"glyph U+{cp:04X} too large for VLW ({bm.width}x{bm.rows})")
        advance = (g.advance.x + 32) >> 6
        metrics += struct.pack(">7i", cp, bm.rows, bm.width, advance, g.bitmap_top, g.bitmap_left, 0)
        for row in range(bm.rows):
            start = row * bm.pitch
            bitmaps += bytes(bm.buffer[start:start + bm.width])

    header = struct.pack(">6i", len(codepoints), 11, px, 0, ascent, descent)
    return header + metrics + bitmaps


def write_header(name, data, px, weight, chars):
    lines = [
        f"// Generated by tools/gen_fonts.py - do not edit.",
        f"// Inter (SIL OFL 1.1), {px} px, weight {weight}, {len(set(chars))} glyphs, {len(data)} bytes.",
        "#pragma once",
        "",
        "#include <pgmspace.h>",
        "#include <stdint.h>",
        "",
        f"const uint8_t {name}[] PROGMEM = {{",
    ]
    for i in range(0, len(data), 24):
        lines.append("  " + ", ".join(f"0x{b:02X}" for b in data[i:i + 24]) + ",")
    lines.append("};")
    (OUT_DIR / f"{name}.h").write_text("\n".join(lines) + "\n")


def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, px, weight, opsz, chars in FONTS:
        data = render_vlw(px, weight, opsz, chars)
        write_header(name, data, px, weight, chars)
        print(f"{name:14s} {px:3d}px w{weight}  {len(data):6d} bytes")


if __name__ == "__main__":
    main()
